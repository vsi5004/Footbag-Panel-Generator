import { readFileSync, writeFileSync } from 'node:fs';
import { format } from 'prettier';

const definitions = JSON.parse(
  readFileSync(new URL('../schema/controls.json', import.meta.url), 'utf8'),
);
const schemaUrl = new URL('../schema/settings.schema.json', import.meta.url);
const htmlUrl = new URL('../index.html', import.meta.url);
const schema = JSON.parse(readFileSync(schemaUrl, 'utf8'));
let html = readFileSync(htmlUrl, 'utf8');
for (const [id, definition] of Object.entries(definitions)) {
  for (const inputId of [id, `${id}Number`]) {
    const pattern = new RegExp(`<input\\b[^>]*id="${inputId}"[^>]*>`, 'g');
    html = html.replace(pattern, (tag) => {
      for (const [name, value] of Object.entries({
        min: definition.min,
        max: definition.max,
        step: definition.step,
        value: definition.default,
      })) {
        tag = tag.replace(new RegExp(`${name}="[^"]*"`), `${name}="${value}"`);
      }
      return tag;
    });
  }
  let properties = schema.properties;
  const path = definition.path.split('.');
  for (const part of path.slice(0, -1)) properties = properties[part].properties;
  const property = properties[path.at(-1)];
  property.minimum = definition.legacySchemaBounds?.[0] ?? definition.min;
  if (!definition.dynamic) property.maximum = definition.legacySchemaBounds?.[1] ?? definition.max;
}
const gcodeDefinitions = JSON.parse(
  readFileSync(new URL('../schema/gcode-controls.json', import.meta.url), 'utf8'),
);
const escapeHtml = (value) =>
  String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('"', '&quot;');
schema.properties.gcode.properties = {};
for (const [key, definition] of Object.entries(gcodeDefinitions)) {
  const { step, labels, ...property } = definition;
  schema.properties.gcode.properties[key] = property;
  const id = `gcode-${key}`;
  if ([...html.matchAll(new RegExp(`id="${id}"`, 'g'))].length !== 1)
    throw new Error(`Expected one HTML control for ${id}`);
  const setAttribute = (tag, name, value) => {
    const pattern = new RegExp(`\\s${name}="[^"]*"`);
    tag = tag.replace(pattern, '');
    return tag.replace(/\s*\/?>(?=$)/, ` ${name}="${escapeHtml(value)}" />`);
  };
  if (definition.type === 'number') {
    html = html.replace(new RegExp(`<input\\b[^>]*id="${id}"[^>]*>`), (tag) => {
      for (const [name, value] of Object.entries({
        min: definition.minimum,
        max: definition.maximum,
        step,
        value: definition.default,
      }))
        tag = setAttribute(tag, name, value);
      return tag;
    });
  } else if (definition.enum) {
    html = html.replace(
      new RegExp(`(<select\\b[^>]*id="${id}"[^>]*>)([\\s\\S]*?)(</select>)`),
      (_, open, _options, close) => {
        const options =
          '\n' +
          definition.enum
            .map(
              (value) =>
                `                  <option value="${escapeHtml(value)}"${value === definition.default ? ' selected' : ''}>${escapeHtml(labels[value])}</option>`,
            )
            .join('\n') +
          '\n                ';
        return open + options + close;
      },
    );
  } else if (definition.type === 'boolean') {
    html = html.replace(new RegExp(`<input\\b[^>]*id="${id}"[^>]*>`), (tag) => {
      tag = tag.replace(/\schecked(?:="[^"]*")?/g, '');
      return definition.default ? tag.replace('>', ' checked>') : tag;
    });
  } else if (definition.type === 'string') {
    html = html.replace(
      new RegExp(`(<textarea\\b[^>]*id="${id}"[^>]*>)[\\s\\S]*?(</textarea>)`),
      (_, open, close) => open + escapeHtml(definition.default) + close,
    );
  }
}
const typeSource = Object.entries(gcodeDefinitions)
  .map(
    ([key, d]) =>
      `  ${key}: ${d.enum ? d.enum.map((v) => JSON.stringify(v)).join(' | ') : d.type};`,
  )
  .join('\n');
const generated = await format(
  `// Generated by scripts/sync-settings.mjs from schema/gcode-controls.json.\nexport interface GcodeSettings {\n${typeSource}\n}\nexport const GCODE_DEFINITIONS = ${JSON.stringify(gcodeDefinitions)} as const;\n`,
  { parser: 'typescript', singleQuote: true, printWidth: 100 },
);
const outputs = [
  [new URL('../src/lib/gcode-definitions.ts', import.meta.url), generated],
  [htmlUrl, html],
  [schemaUrl, `${JSON.stringify(schema, null, 2)}\n`],
];
for (const [url, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (readFileSync(url, 'utf8').replaceAll('\r\n', '\n') !== content.replaceAll('\r\n', '\n')) {
      console.error(`${url.pathname} is out of sync; run npm run settings:sync`);
      process.exitCode = 1;
    }
  } else writeFileSync(url, content);
}
